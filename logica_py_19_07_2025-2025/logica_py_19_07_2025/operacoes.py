num1 = float(input("digite o primeiro numero: "))
num2 = float(input("digite o segundo numero: "))
operador= input("DIGITE O operadorERADOR AGORA( +, -, *, //)")

if operador == '+':
       print(num1 + num2)
elif operador == '-':
       print(num1 - num2)
elif operador == '*':
       print(num1 * num2)
elif operador == '//':
       print(num1 // num2)

